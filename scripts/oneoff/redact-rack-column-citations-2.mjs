// Rack columns, batch 2 — dominated by one sentence written seventeen times.
//
// THE DIKES CLUSTER. Seventeen single-pitch sport routes carry the same construction:
//
//     "Single-pitch bolted sport route at Megadike North (The Dikes, WA); confirmed as Sport,
//      3-star, on Mountain Project's official area page."
//
// The clause is REDUNDANT as well as a citation — the value has already said "bolted sport
// route", so "confirmed as Sport" restates it, and the star rating is a website's score rather
// than a fact about the rock (the page-views-are-not-ascents class). The whole clause goes; the
// rope advice after it, which is the only thing a climber needs, is untouched.
//
// AND ONE WORKING-LANGUAGE LEAK, in a rope note of all places. wa_austera_peak_southwest_ridge
// ends: "if the prior autoGenerated text specified double ropes, that was an unsupported
// generic-alpine assumption and SHOULD BE CORRECTED to a single 60m rope." That is an
// instruction to a pipeline, naming an internal flag, rendered to a climber deciding what rope
// to carry. It is cut, and the conclusion it was arguing for — a single 60 m rope is enough —
// is stated plainly instead.
//
// DOCUMENTED NEGATIVES KEEP THEIR FINDING. "No route-specific beta found ... on Mountain
// Project, OpenBeta, or SummitPost" and "Area not found on Mountain Project's index or other
// guidebook sources searched" both survive as statements that nothing is published; only the
// list of places somebody looked goes.
//
