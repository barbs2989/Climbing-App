// Would the provenance chip SAY ANYTHING, or just print one word everywhere?
//
// #806 landed the principle this has to answer to: two page-level graders were deleted for
// "grading every route whether or not it had anything to say, which is what made it noise",
// and its gear caption stays SILENT on the verified majority for exactly that reason. If my
// per-section chip reads "On file" on ~everything, it is the same noise I criticised
// data_quality.confidence for — so measure before shipping it, not after.
import { selectAll } from "../lib/supabase-env.mjs";
import { SECTIONS, sectionProvenance } from "../../lib/provenance.js";

const COLS = "id,beta,approach,descent_text,rappels,rappel_detail,pitch_detail,season,best_season,gear,rack,waypoints,gpx,hazards,obj_haz,watch_out,climate,auto_generated,gear_confidence";
const rows = await selectAll("routes", COLS, "id=like.wa_*", { pageSize: 1000 });
console.log(`scanned ${rows.length} WA routes\n`);

// mirror dbRouteToCamel for just the keys sectionProvenance reads
const camel = (r) => ({
  beta: Array.isArray(r.beta) ? r.beta : (r.beta ? [r.beta] : []),
  approach: r.approach, descentText: r.descent_text, rappels: r.rappels,
  rappelDetail: r.rappel_detail, pitchDetail: r.pitch_detail, season: r.season,
  bestSeason: r.best_season, gear: r.gear, rack: r.rack, waypoints: r.waypoints,
  gpxPts: r.gpx, hazards: r.hazards, objHaz: r.obj_haz, watchOut: r.watch_out,
  climate: r.climate, autoGenerated: r.auto_generated, gearConfidence: r.gear_confidence,
});

const names = Object.keys(SECTIONS);
const pad = (s, n) => String(s).padEnd(n);
console.log(pad("section", 14) + pad("has data", 10) + pad("verified", 10) + pad("On file", 10) + pad("Auto-gen", 10) + "verdict");
let totalChips = 0, totalOnFile = 0;
for (const name of names) {
  const t = { verified: 0, onfile: 0, auto: 0, none: 0 };
  for (const r of rows) {
    const p = sectionProvenance(camel(r), name);
    t[p ? p.level : "none"]++;
  }
  const withData = rows.length - t.none;
  totalChips += withData; totalOnFile += t.onfile;
  const pct = (n) => withData ? ((n / withData) * 100).toFixed(1) + "%" : "-";
  const verdict = !withData ? "never renders" : (t.onfile / withData > 0.95 ? "*** ONE WORD EVERYWHERE — noise ***" : "discriminates");
  console.log(pad(name, 14) + pad(withData, 10) + pad(pct(t.verified), 10) + pad(pct(t.onfile), 10) + pad(pct(t.auto), 10) + verdict);
}
console.log(`\nACROSS ALL SECTIONS: ${totalChips} chips would render, ${((totalOnFile / totalChips) * 100).toFixed(1)}% of them saying "On file".`);
console.log(`A chip is worth showing only where it can be something other than the default.`);
