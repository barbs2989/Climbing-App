/* Does the provenance chip actually REACH A SCREEN, and does it say the right thing?
 *
 * A green build proves only that nothing threw. `descent_text` was populated on 1,021 routes
 * and rendered on none while every static gate stayed green — presence is not reachability, so
 * this renders the real RouteDetail and looks for the label.
 *
 * It also pins the honesty rule the design rests on: a section with NO data must carry NO
 * chip. That case is the one a careless refactor breaks (defaulting a null level to "Low"),
 * and it is invisible to every other guard.
 *
 * Run: node scripts/check-provenance-chips.mjs
 */
import { sectionProvenance, PROV } from "../lib/provenance.js";

let fail = 0;
const t = (name, got, want) => {
  const ok = got === want;
  if (!ok) fail++;
  console.log(`  ${ok ? "ok  " : "FAIL"}  ${name}: got ${JSON.stringify(got)} want ${JSON.stringify(want)}`);
};
const lvl = (r, s) => { const p = sectionProvenance(r, s); return p ? p.level : null; };

console.log("1. a section with NO data carries NO chip (GapNote owns the empty case)");
t("bare route, approach", lvl({}, "approach"), null);
t("empty string is empty", lvl({ approach: "   " }, "approach"), null);
t("empty array is empty", lvl({ waypoints: [] }, "waypoints"), null);
t("empty object is empty", lvl({ gearTiers: {} }, "gear"), null);

console.log("\n2. enrichment on file reads On file");
t("approach prose", lvl({ approach: "Hike the Blue Lake trail." }, "approach"), "onfile");
t("descent via descentText", lvl({ descentText: "Walk off east." }, "descentText"), "onfile");
t("descent via legacy descent", lvl({ descent: "Walk off east." }, "descentText"), "onfile");
t("rappels via rappelDetail only", lvl({ rappelDetail: [{ n: 1 }] }, "rappels"), "onfile");

console.log("\n3. auto_generated weakens a section that has no stronger signal");
t("autoGenerated route", lvl({ approach: "x", autoGenerated: true }, "approach"), "auto");
t("autoGenerated=false is On file", lvl({ approach: "x", autoGenerated: false }, "approach"), "onfile");

console.log("\n4. a climber's accepted edit outranks auto_generated");
t("contrib approach beats auto", lvl({ approach: "x", autoGenerated: true, _contribFields: ["approach"] }, "approach"), "verified");
t("contrib uses FORM keys, not property names", lvl({ rappels: "3", _contribFields: ["rap"] }, "rappels"), "verified");
t("the property name must NOT match", lvl({ rappels: "3", _contribFields: ["rappels"] }, "rappels"), "onfile");
t("legacy _rappelsFromContrib still counts", lvl({ rappels: "3", _rappelsFromContrib: true }, "rappels"), "verified");
t("an unrelated field does not claim this section", lvl({ approach: "x", _contribFields: ["beta"] }, "approach"), "onfile");

console.log("\n5. gear_confidence is the one real per-section column");
t("gear verified", lvl({ gear: ["cams"], gearConfidence: "verified" }, "gear"), "verified");
t("gear inferred", lvl({ gear: ["cams"], gearConfidence: "inferred" }, "gear"), "auto");
t("gear absent -> On file", lvl({ gear: ["cams"] }, "gear"), "onfile");
t("gearConfidence does NOT leak to other sections", lvl({ approach: "x", gearConfidence: "verified" }, "approach"), "onfile");

console.log("\n6. data_quality.confidence must NOT drive anything (94% MEDIUM)");
t("MEDIUM does not become a level", lvl({ approach: "x", dataQuality: { confidence: "MEDIUM" } }, "approach"), "onfile");
t("even HIGH does not", lvl({ approach: "x", dataQuality: { confidence: "HIGH" } }, "approach"), "onfile");

console.log("\n7. the labels are the three the design promises");
t("verified label", PROV.verified.label, "Climber-verified");
t("onfile label", PROV.onfile.label, "On file");
t("auto label", PROV.auto.label, "Auto-generated");

console.log("\n8. it REACHES A SCREEN — render the real RouteDetail and find the label");
/* Node cannot import .jsx, so bundle first — the same esbuild harness check:bare uses.
   QueryClientProvider is required: RouteDetail calls react-query hooks. */
const { build } = await import("esbuild");
const { createRequire } = await import("module");
const fs = (await import("fs")).default, os = (await import("os")).default, path = (await import("path")).default;
const { fileURLToPath } = await import("url");
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require_ = createRequire(import.meta.url);
const ENTRY = `
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import RouteDetail from ${JSON.stringify(path.join(ROOT, "RouteDetail.jsx"))};
const qc = new QueryClient({ defaultOptions: { queries: { retry: false } } });
const noop = () => {};
export function render(route, tab) {
  return renderToStaticMarkup(
    React.createElement(QueryClientProvider, { client: qc },
      React.createElement(RouteDetail, {
        route, initialSubTab: tab, onBack: noop, onSubTab: noop,
        contribs: [], myReports: [], connections: [], comments: {},
        hzVotes: {}, sunReports: {}, gearEdits: {}, diffRatings: {},
        crewsForRoute: [], myStars: {}, presence: null,
      })));
}
`;
const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), "cm-prov-")), "bundle.cjs");
await build({
  stdin: { contents: ENTRY, resolveDir: ROOT, loader: "js" },
  bundle: true, format: "cjs", platform: "node", jsx: "automatic",
  loader: { ".jsx": "jsx" }, define: { "import.meta.env": "{}" },
  outfile: out, logLevel: "error",
});
const { render } = require_(out);

const routeWith = (extra) => Object.assign({
  id: "probe_trad", name: "Probe Route", grade: "5.6", gradeSystem: "yds",
  discipline: "trad", pitches: 6, mountainId: "probe_area",
  _dbArea: { id: "probe_area", name: "Probe Area", areaType: "crag", region: "Colorado" },
}, extra);

function markup(extra) {
  try { return render(routeWith(extra), "planner"); }
  catch (e) { return "RENDER THREW: " + e.message; }
}

const withApproach = markup({ approach: "Hike the Blue Lake trail 1.2 mi to the notch." });
const bare = markup({});

const sawOnFile = withApproach.includes("On file");
const bareHasNoChip = !bare.includes("On file") && !bare.includes("Auto-generated") && !bare.includes("Climber-verified");
if (withApproach.startsWith("RENDER THREW")) { console.log("  FAIL  " + withApproach.slice(0, 200)); fail++; }
else {
  t("populated approach renders an 'On file' chip", sawOnFile, true);
  /* HONEST ABOUT WHAT THIS ONE PROVES: it passes even when sectionProvenance is broken to
     rate absent data, because a bare route's sections are content-gated and never render at
     all — so no SL exists to hang a chip on either way. Measured, not assumed: injecting
     `return PROV.onfile` for absent data fails the four assertions in section 1 above and
     leaves this one green. Keep it as a belt-and-braces check on the rendered output, but the
     honesty rule is enforced by section 1, not here. */
  t("a BARE route renders no chip at all (weak — see comment)", bareHasNoChip, true);
}

/* INJECTION TESTS (both run, both caught, 2026-08-12):
 *   1. Disable the chip render in SL (`{false&&prov&&...}`) — section 8 fails naming the
 *      'On file' chip, real exit code 1. Confirms the guard is not vacuous.
 *   2. `return PROV.onfile` for absent data in sectionProvenance — section 1 fails all four
 *      emptiness assertions. Confirms the honesty rule is actually pinned.
 * Re-run both after changing the traversal or the section table. */

console.log(fail ? `\ncheck:provenance-chips: ${fail} FAILING` : "\ncheck:provenance-chips: ok — all assertions passed");
process.exit(fail ? 1 : 0);
