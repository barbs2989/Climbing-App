// Regenerates SUPABASE_SCHEMA.sql from the LIVE `public` schema: every table's CREATE TABLE
// (columns, types, NOT NULL, defaults, identity, primary/unique/check/foreign keys), its RLS
// flags and its CREATE POLICY statements. Read-only: one SELECT through the linked CLI.
//
//   npm run gen:schema          rewrite SUPABASE_SCHEMA.sql from the live database
//   npm run gen:schema -- --check   exit 1 if the committed file no longer matches live
//
// Needs the link state (supabase/.temp) — see docs/codebase/supabase-scripts.md. Not run by
// `npm run build`: the build must never reach the live database.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "SUPABASE_SCHEMA.sql");
const CHECK = process.argv.includes("--check");

// quote_ident() quotes only what PostgreSQL would otherwise misread (keywords, capitals), so the
// generated names are the exact spelling the database uses.
const SQL = `
select json_build_object(
  'tables', (select coalesce(json_agg(json_build_object(
              'name', quote_ident(c.relname), 'rls', c.relrowsecurity, 'force', c.relforcerowsecurity)
              order by c.relname), '[]'::json)
            from pg_class c join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and c.relkind in ('r', 'p')),
  'columns', (select coalesce(json_agg(json_build_object(
              'table', quote_ident(c.relname), 'pos', a.attnum, 'name', quote_ident(a.attname),
              'type', format_type(a.atttypid, a.atttypmod), 'not_null', a.attnotnull,
              'default', pg_get_expr(d.adbin, d.adrelid), 'identity', a.attidentity,
              'generated', a.attgenerated)
              order by c.relname, a.attnum), '[]'::json)
            from pg_attribute a
            join pg_class c on c.oid = a.attrelid
            join pg_namespace n on n.oid = c.relnamespace
            left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
            where n.nspname = 'public' and c.relkind in ('r', 'p')
              and a.attnum > 0 and not a.attisdropped),
  'constraints', (select coalesce(json_agg(json_build_object(
              'table', quote_ident(c.relname), 'name', quote_ident(k.conname),
              'type', k.contype, 'def', pg_get_constraintdef(k.oid))
              order by c.relname, k.contype, k.conname), '[]'::json)
            from pg_constraint k
            join pg_class c on c.oid = k.conrelid
            join pg_namespace n on n.oid = c.relnamespace
            where n.nspname = 'public' and k.contype in ('p', 'u', 'c', 'f')),
  'policies', (select coalesce(json_agg(json_build_object(
              'table', quote_ident(p.tablename), 'name', quote_ident(p.policyname),
              'permissive', p.permissive, 'roles', p.roles, 'cmd', p.cmd,
              'qual', p.qual, 'with_check', p.with_check)
              order by p.tablename, p.policyname), '[]'::json)
            from pg_policies p where p.schemaname = 'public')
) as schema;`;

const tmp = path.join(process.env.CLAUDE_JOB_DIR || os.tmpdir(), "gen-supabase-schema.sql");
fs.writeFileSync(tmp, SQL);
let raw;
try {
  raw = execFileSync("npx", ["supabase", "db", "query", "--linked", "-o", "json", "-f", tmp],
    { encoding: "utf8", timeout: 180000, maxBuffer: 64 * 1024 * 1024, cwd: ROOT });
} catch (e) {
  console.error("FAIL: could not read the live catalog —", String(e.message).split("\n")[0].slice(0, 200));
  console.error("      A fresh worktree is not LINKED. Check: npx supabase projects list");
  process.exit(1);
}
const start = raw.indexOf("{"), end = raw.lastIndexOf("}");
let schema;
try {
  const outer = JSON.parse(raw.slice(start, end + 1));
  const rows = outer.rows || outer.result || outer;
  schema = (Array.isArray(rows) ? rows[0] : rows).schema;
} catch (e) { console.error("FAIL: could not parse the catalog —", e.message); process.exit(1); }
if (!schema || !schema.tables?.length) {
  console.error("FAIL: the live catalog came back empty. An empty read means the scan broke,");
  console.error("      never that the database has no tables. Not writing the file.");
  process.exit(1);
}

// ── build the document ───────────────────────────────────────────────────────
const byTable = (rows) => {
  const m = new Map();
  for (const r of rows) { if (!m.has(r.table)) m.set(r.table, []); m.get(r.table).push(r); }
  return m;
};
const cols = byTable(schema.columns), cons = byTable(schema.constraints), pols = byTable(schema.policies);
const CON_ORDER = { p: 0, u: 1, c: 2, f: 3 };
const identity = (i) => (i === "a" ? " GENERATED ALWAYS AS IDENTITY" : i === "d" ? " GENERATED BY DEFAULT AS IDENTITY" : "");

function columnLine(c) {
  let s = `  ${c.name} ${c.type}`;
  if (c.not_null) s += " NOT NULL";
  if (c.generated === "s") s += ` GENERATED ALWAYS AS (${c.default}) STORED`;
  else if (c.default != null) s += ` DEFAULT ${c.default}`;
  return s + identity(c.identity);
}

const tables = schema.tables;
const fkRows = schema.constraints.filter((k) => k.type === "f");
const out = [];
out.push("-- SUPABASE_SCHEMA.sql");
out.push("--");
out.push("-- The live `public` schema of the ClimbMatch Supabase project: every table's CREATE TABLE,");
out.push("-- its foreign keys, data types, row-level security and RLS policies.");
out.push("--");
out.push("-- GENERATED from the live database by scripts/gen-supabase-schema.mjs. Do not hand-edit.");
out.push("-- After ANY change to the database structure (a migration, a dashboard edit, a DDL run):");
out.push("--     npm run gen:schema");
out.push("-- and commit the result in the same PR. `npm run gen:schema -- --check` exits 1 when this");
out.push("-- file has drifted from the live database.");
out.push("--");
out.push(`-- Counts: ${tables.length} tables, ${schema.columns.length} columns, ${schema.constraints.length} keyed/checked constraints (${fkRows.length} foreign keys), ${schema.policies.length} RLS policies.`);
out.push("-- Not covered here: views, functions, triggers, standalone indexes (see supabase/migrations/).");
out.push("");
out.push("-- ── Foreign keys ───────────────────────────────────────────────────────────────");
for (const k of fkRows) out.push(`-- ${k.table} (${k.name}): ${k.def}`);
out.push("");
out.push("-- ── Tables, RLS and policies ───────────────────────────────────────────────────");
for (const t of tables) {
  out.push("");
  const items = [
    ...(cols.get(t.name) || []).map(columnLine),
    ...(cons.get(t.name) || [])
      .slice().sort((a, b) => CON_ORDER[a.type] - CON_ORDER[b.type])
      .map((k) => `  CONSTRAINT ${k.name} ${k.def}`),
  ];
  out.push(`CREATE TABLE public.${t.name} (`);
  out.push(items.join(",\n"));
  out.push(");");
  out.push(`ALTER TABLE public.${t.name} ${t.rls ? "ENABLE" : "DISABLE"} ROW LEVEL SECURITY;`);
  if (t.force) out.push(`ALTER TABLE public.${t.name} FORCE ROW LEVEL SECURITY;`);
  for (const p of pols.get(t.name) || []) {
    let s = `CREATE POLICY ${p.name} ON public.${t.name} AS ${p.permissive} FOR ${p.cmd} TO ${p.roles.join(", ")}`;
    if (p.qual != null) s += ` USING (${p.qual})`;
    if (p.with_check != null) s += ` WITH CHECK (${p.with_check})`;
    out.push(s + ";");
  }
}
const doc = out.join("\n") + "\n";

if (CHECK) {
  const committed = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (committed !== doc) {
    console.error("FAIL: SUPABASE_SCHEMA.sql no longer matches the live database.");
    console.error("      Run: npm run gen:schema   (then commit the result)");
    process.exit(1);
  }
  console.log(`OK: SUPABASE_SCHEMA.sql matches the live database (${tables.length} tables, ${schema.policies.length} policies).`);
  process.exit(0);
}
fs.writeFileSync(OUT, doc);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${tables.length} tables, ${schema.columns.length} columns, ${fkRows.length} foreign keys, ${schema.policies.length} policies.`);
