// Merge the reviewed summit verdicts into the committed audit and the app's deny map.
//
//   node scripts/build-list-summit-audit.mjs
//
// Reads research-data/list-summit-audit/census.json (scripts/audit-list-summit-routes.mjs) and
// every verdicts-*.json next to it (one reviewer pass per chunk, or a later pass for new routes),
// then writes:
//   research-data/list-summit-audit/audit.json  every reviewed route and area, with reasons
//   lib/listSummit.js                           NOT_SUMMIT: the route ids that must never tick a peak
//
// A verdicts file later BY NAME wins over an earlier one for the same id, so a correction is a new
// verdicts-zz-<name>.json rather than an edit to a reviewer's output.
import fs from "node:fs";
import path from "node:path";
import { PEAK_ROSTERS } from "../lib/lists.js";

const DIR = "research-data/list-summit-audit";
const census = JSON.parse(fs.readFileSync(path.join(DIR, "census.json"), "utf8"));
const files = fs.readdirSync(DIR).filter(f => /^verdicts-.*\.json$/.test(f)).sort(); // by NAME, not mtime (a checkout resets mtimes): name corrections verdicts-zz-*.json so they apply last
const verdict = new Map(), areaVerdict = new Map();
for (const f of files) {
  const v = JSON.parse(fs.readFileSync(path.join(DIR, f), "utf8"));
  for (const r of v.routes || []) verdict.set(r.id, { ...r, source: f });
  for (const a of v.areas || []) areaVerdict.set(a.area, { ...a, source: f });
}
const routes = census.routes.map(r => {
  const v = verdict.get(r.id);
  return { id: r.id, name: r.name, peak: r.peak, area: r.area, discipline: r.discipline, grade: r.grade,
    summits: v ? !!v.summits : null, confidence: v ? v.confidence : null, reason: v ? v.reason : null };
});
const missing = routes.filter(r => r.summits === null);
if (missing.length) {
  console.error(`${missing.length} census route(s) have no verdict, e.g. ${missing.slice(0, 5).map(r => r.id).join(", ")}`);
  process.exit(1);
}
const reviewedAreas = [];
for (const peaks of Object.values(PEAK_ROSTERS)) for (const p of peaks) for (const a of [p.id, ...(p.also || [])]) if (!reviewedAreas.includes(a)) reviewedAreas.push(a);
const audit = {
  note: "Which routes on a peak-list peak reach that peak's summit. Built by scripts/build-list-summit-audit.mjs; checked by scripts/check-list-summit-audit.mjs.",
  census: census.generated,
  reviewedAreas: reviewedAreas.sort(),
  // An `also` area is DETACHED from its peak only when the reviewer said so AND none of its routes
  // reach the summit; a mixed area (Shuksan's summit pyramid with one crag pitch) stays attached and
  // its stray routes are refused one by one in NOT_SUMMIT.
  areas: [...areaVerdict.values()].map(({ source, ...a }) => {
    const summitRoute = routes.find(r => r.area === a.area && r.summits);
    const keepArea = !!a.keepArea || !!summitRoute;
    return { ...a, keepArea, reason: a.keepArea || !summitRoute ? a.reason : `${a.reason} (kept: ${summitRoute.id} reaches the summit)` };
  }).sort((a, b) => a.area.localeCompare(b.area)),
  routes,
};
fs.writeFileSync(path.join(DIR, "audit.json"), JSON.stringify(audit, null, 1) + "\n");

const deny = routes.filter(r => !r.summits).sort((a, b) => a.id.localeCompare(b.id));
const esc = s => JSON.stringify(String(s || "").replace(/\s+/g, " ").trim());
const lines = deny.map(r => `  ${JSON.stringify(r.id)}: ${esc(`${r.peak}: ${r.reason}`)},`);
const lib = `// GENERATED by scripts/build-list-summit-audit.mjs from research-data/list-summit-audit/ - do not hand-edit.
//
// A PEAK LIST is ticked by standing on the summit. lib/lists.js counts a peak when a logged route
// sits on the peak's area (or one of its \`also\` faces), and that area also holds climbs that never
// reach the top: a V1 at the base of Castleton Tower, a crag on Pikes Peak's flank, an ice flow in
// McCullough Gulch, a start variation. Each was reviewed (audit.json there gives every route's
// verdict and reason) and the ones that stop short are listed here, so they cannot tick the peak
// or wear the list's chip.
//
// Bouldering and top-rope are refused by discipline as well, so a problem added to a list peak
// after this audit is refused before anyone reviews it.

/** Route id -> why climbing it does not put you on the list peak's summit. */
export const NOT_SUMMIT = {
${lines.join("\n")}
};

const NEVER_SUMMIT = new Set(["bouldering", "boulder", "toprope", "top-rope"]);

/** Does climbing this route put you on top of the peak its area belongs to? */
export function reachesSummit(route) {
  if (!route) return false;
  const d = String(route.discipline || "").toLowerCase();
  const s = String(route.style || "").toLowerCase();
  if (NEVER_SUMMIT.has(d) || NEVER_SUMMIT.has(s)) return false;
  return !Object.prototype.hasOwnProperty.call(NOT_SUMMIT, String(route.id));
}
`;
fs.writeFileSync("lib/listSummit.js", lib);
const low = routes.filter(r => r.confidence === "low");
console.log(`routes ${routes.length}: summit ${routes.length - deny.length}, not summit ${deny.length}, low confidence ${low.length}; areas reviewed ${audit.areas.length}, dropped ${audit.areas.filter(a => !a.keepArea).length}`);
