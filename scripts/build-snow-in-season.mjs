// Builds lib/snowInSeasonDry.js from the per-route review in research-data/snow-in-season-2026-11-12/.
//
// Owner, 2026-11-12: the freezing-level and refreeze flags only matter for routes that cross a glacier or
// snow on a normal (peak-season) summit day. Each alpine-rock / scramble route whose text mentions snow was
// read and marked yes / no / unsure (RULE.md there). Only "no" goes in the list; "unsure" keeps the flags.
//
//   node scripts/build-snow-in-season.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "research-data", "snow-in-season-2026-11-12");
const dec = JSON.parse(fs.readFileSync(path.join(DIR, "decisions.json"), "utf8"));
const dry = dec.filter((d) => d.final === "no").map((d) => d.id).sort();
const body = "// GENERATED by scripts/build-snow-in-season.mjs from research-data/snow-in-season-2026-11-12/decisions.json.\n" +
  "// Alpine-rock and scramble routes whose own text mentions snow, reviewed as crossing NO snow or glacier on a\n" +
  "// normal peak-season summit day (owner, 2026-11-12). lib/terrain.js reads them as snowInSeason \"no\", which drops\n" +
  "// the freezing-level, refreeze and snow-softening logic (lib/alpineConditions.js hasSnowLegs). Do not hand-edit.\n" +
  "export const SNOW_DRY_IN_SEASON = new Set(" + JSON.stringify(dry, null, 0).replace(/","/g, "\",\n  \"").replace(/^\["/, "[\n  \"").replace(/"\]$/, "\"\n]") + ");\n";
fs.writeFileSync(path.join(ROOT, "lib", "snowInSeasonDry.js"), body);
console.log("wrote lib/snowInSeasonDry.js:", dry.length, "routes dry in season");
